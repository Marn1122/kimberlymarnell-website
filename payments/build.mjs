// Makes ONE file to paste into the Cloudflare dashboard editor: upload/worker.js
// Run after any change to artistsforcommission/artists.js or worker.js:  node build.mjs
import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from 'node:fs';
copyFileSync('../artistsforcommission/artists.js', 'artists.js');
const artists = readFileSync('artists.js', 'utf8');
const worker = readFileSync('worker.js', 'utf8').replace("import './artists.js';", '/* artists.js is included above */');
mkdirSync('upload', { recursive: true });
writeFileSync('upload/worker.js', '/* GENERATED by build.mjs — do not edit. Edit artistsforcommission/artists.js and payments/worker.js instead. */\n' + artists + '\n' + worker);
console.log('upload/worker.js written');
